def load_phase_e_precision_artifact() -> dict:
    record = json.loads(PHASE_E_PRECISION_PATH.read_bytes())
    material = dict(record)
    digest = material.pop("artifact_digest", None)
    expected = hashlib.sha256(json.dumps(
        material, sort_keys=True, separators=(",", ":"), allow_nan=False,
    ).encode()).hexdigest()
    freeze = load_prospective_phase_d_final_freeze()
    if (digest != PHASE_E_PRECISION_ARTIFACT_DIGEST or digest != expected
        or record["phase_d_final_freeze_artifact_digest"] != freeze["artifact_digest"]
        or record["source_d6_json_sha256"] != freeze["evidence"]["phase_d6"]["json_sha256"]
        or record["precision"]["planned_reserved_blocks"] != RESERVED_BLOCKS):
        raise ValueError("Phase E precision artifact is not the frozen development projection")
    return record


def phase_e_precision_payload() -> dict:
    freeze = load_prospective_phase_d_final_freeze()
    groups = {
        SELECTOR_PROCEDURE: freeze["internal_check_result"]["metrics"]["by"]["truth_family"],
        **{policy: freeze["fixed_policy_comparators"][policy]["by"]["truth_family"]
           for policy in POLICY_NAMES},
    }
    result = precision_projection(groups, reserved_blocks=RESERVED_BLOCKS)
    # A four-worker ideal is a lower estimate, not a promised wall duration.
    cpu_hours = freeze["runtime"]["aggregate_block_cpu_seconds"] / 3600 * CALIBRATION_BLOCKS / 10
    result["compute_projection"] = {
        "source": "closed Phase D6 resource record bound in final Phase D freeze",
        "calibration_block_count": CALIBRATION_BLOCKS,
        "approximate_cpu_hours_per_100_block_partition": cpu_hours,
        "ideal_four_worker_wall_hours": cpu_hours / 4,
        "planning_wall_hours_per_partition": [43, 60],
        "planning_raw_block_archive_bytes": freeze["evidence"]["phase_d6"]["archive_size_bytes"] * 10,
        "final_calibration_summary_indexes_raw_blocks_without_duplicating_them": True,
        "planning_disk_budget_including_disposable_probe_bytes": 2 * 1024**3,
        "wall_projection_includes_no_claim_about_unrecorded_prior_invocations": True,
    }
    result["size_decision"] = (
        "Retain 100 calibration and 100 reserved blocks within the reviewed compute plan. "
        "The conservative simultaneous risk bounds are expected to be inconclusive; "
        "no 2-percentage-point risk noninferiority claim is promised. Do not extend after outcomes."
    )
    return result


