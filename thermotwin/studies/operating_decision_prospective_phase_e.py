def phase_e_protocol_digest(*, source_revision: str, source_manifest_digest: str) -> str:
    return _digest(f"{PHASE_E_DOMAIN}.protocol_v1", phase_e_protocol_payload(
        source_revision=source_revision, source_manifest_digest=source_manifest_digest,
    ))


def validate_phase_e_protocol(payload: Mapping[str, object]) -> dict:
    expected = phase_e_protocol_payload(
        source_revision=payload.get("source_revision"),
        source_manifest_digest=payload.get("source_manifest_digest"),
    )
    if payload != expected:
        raise ValueError("Phase E protocol differs from the frozen analysis design")
    return deepcopy(expected)
